-- 2. Customers
CREATE TABLE IF NOT EXISTS public.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    tax_id TEXT DEFAULT '',
    address TEXT DEFAULT '',
    phone TEXT DEFAULT '',
    email TEXT DEFAULT '',
    note TEXT DEFAULT '',
    deleted_at TIMESTAMPTZ DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Customer Projects / Sub-billing (หลายโครงการต่อ 1 ลูกค้า)
CREATE TABLE IF NOT EXISTS public.customer_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES public.customers(id) ON DELETE CASCADE,
    project_name TEXT NOT NULL,
    site_address TEXT DEFAULT '',
    contact_person TEXT DEFAULT '',
    note TEXT DEFAULT '',
    deleted_at TIMESTAMPTZ DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Document Sequences (รันเลขที่เอกสาร Zero Collision)
CREATE TABLE IF NOT EXISTS public.document_sequences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_type TEXT NOT NULL, -- 'quotation', 'billing', 'receipt'
    year_month TEXT NOT NULL, -- เช่น '202611' หรือ '256911'
    current_number INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(doc_type, year_month)
);

-- 5. Document Reservations (เลขที่กันไว้/จองไว้ออกบิลย้อนหลัง)
CREATE TABLE IF NOT EXISTS public.document_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_type TEXT NOT NULL, -- 'quotation', 'billing', 'receipt'
    code TEXT NOT NULL UNIQUE, -- เช่น 'QT202611-005'
    customer_id BIGINT REFERENCES public.customers(id) ON DELETE SET NULL,
    project_id BIGINT REFERENCES public.customer_projects(id) ON DELETE SET NULL,
    note TEXT DEFAULT '',
    status TEXT NOT NULL DEFAULT 'reserved', -- 'reserved', 'used', 'cancelled'
    reserved_at TIMESTAMPTZ DEFAULT NOW(),
    used_at TIMESTAMPTZ DEFAULT NULL
);

-- 6. Documents (เอกสารหลัก)
CREATE TABLE IF NOT EXISTS public.documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT NOT NULL UNIQUE, -- เช่น 'QT202611-001'
    type TEXT NOT NULL, -- 'quotation', 'billing', 'receipt'
    customer_id BIGINT NOT NULL REFERENCES public.customers(id),
    project_id BIGINT REFERENCES public.customer_projects(id),
    project_name_custom TEXT DEFAULT '',
    reference_document_id BIGINT REFERENCES public.documents(id) ON DELETE SET NULL,
    issue_date DATE NOT NULL,
    due_date DATE DEFAULT NULL,
    subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0,
    discount_total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    vat_amount NUMERIC(12, 2) NOT NULL DEFAULT 0, -- 0.00 เนื่องจากร้านไม่มี VAT
    grand_total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'issued', -- 'draft', 'issued', 'paid', 'cancelled'
    remark TEXT DEFAULT '',
    payment_terms TEXT DEFAULT '',
    cancel_reason TEXT DEFAULT '',
    cancelled_at TIMESTAMPTZ DEFAULT NULL,
    deleted_at TIMESTAMPTZ DEFAULT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Document Items (รายการสินค้าในเอกสาร รองรับรูป Thumbnail)
CREATE TABLE IF NOT EXISTS public.document_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL REFERENCES public.documents(id) ON DELETE CASCADE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    product_name TEXT NOT NULL,
    image_url TEXT DEFAULT '',
    quantity NUMERIC(10, 2) NOT NULL DEFAULT 1,
    unit TEXT NOT NULL DEFAULT 'ชิ้น',
    unit_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    discount NUMERIC(12, 2) NOT NULL DEFAULT 0,
    discount_type TEXT NOT NULL DEFAULT 'amount',
    total_price NUMERIC(12, 2) NOT NULL DEFAULT 0
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_customers_deleted ON public.customers(deleted_at);
CREATE INDEX IF NOT EXISTS idx_projects_customer ON public.customer_projects(customer_id, deleted_at);
CREATE INDEX IF NOT EXISTS idx_docs_type_status ON public.documents(type, status, deleted_at);
CREATE INDEX IF NOT EXISTS idx_docs_customer ON public.documents(customer_id, deleted_at);
CREATE INDEX IF NOT EXISTS idx_docs_issue_date ON public.documents(issue_date);
CREATE INDEX IF NOT EXISTS idx_doc_items_doc ON public.document_items(document_id, sort_order);
CREATE INDEX IF NOT EXISTS idx_reservations_type_status ON public.document_reservations(doc_type, status);

